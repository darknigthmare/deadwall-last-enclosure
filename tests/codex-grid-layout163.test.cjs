const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const Q=require('../src/codex3000-recipes159.js'),P=require('../src/codex-plan165.js');
const hash=value=>crypto.createHash('sha256').update(JSON.stringify(value)).digest('hex');

test('163 shared grid layout retains ground approaches and exact upper/basement cell coordinates',()=>{
 const p={w:24,h:18},ground=Q.gridLayout(p,0),upper=Q.gridLayout(p,1),basement=Q.gridLayout(p,-1);
 assert.deepEqual(ground,{cell:.4,left:-12,top:-16,right:36,bottom:43,cols:120,rows:148,size:17760});
 assert.deepEqual(upper,{cell:.4,left:-0,top:0,right:24,bottom:18,cols:60,rows:45,size:2700});assert.deepEqual(basement,upper);
 const plan={walls:[],objects:[],stairs:[],rooms:[]},detail={interior:[],outdoor:[]};
 for(const z of [-1,0,1]){
  const layout=Q.gridLayout(p,z),grid=Q.accessGrid(p,z,plan,detail);
  assert.equal(grid.reachable.length,layout.size);assert.ok(grid.baseline);
  for(const [col,row]of [[0,0],[1,1],[layout.cols-1,layout.rows-1],[Math.floor(layout.cols/2),Math.floor(layout.rows/2)]]){
   const x=layout.left+(col+.5)*layout.cell,y=layout.top+(row+.5)*layout.cell;
   assert.equal(grid.at(x,y),row*layout.cols+col);assert.ok(grid.reachable[grid.at(x,y)]);
  }
 }
});

