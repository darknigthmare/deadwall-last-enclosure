test('162 G10 furnishing: only326 preserved interiors gain revision11 props; finite plans, services and special domains stay intact',()=>{
 const {old,next}=worlds();let interiors=0,floors=0,added=0,solids=0,services=0,checkedBodies=0;
 for(const p of next.contextSites160()){
  const before=old.pois.find(site=>site.id===p.id);assert.equal(before.programme160,p.programme160);
  for(const z of p.levels){const plan=next.plan(p,z),prior=old.plan(before,z),serialized=hash([p,plan]),detail=next.detailAt(p,z);
   assert.deepEqual(plan,prior,p.programme160+' keeps exact source geometry and finite container identities');
   if(p.context160.profile){assert.deepEqual(detail,old.detailAt(before,z));continue;}
   if(z===0)interiors++;floors++;assert.ok(detail.interior.length+detail.outdoor.length>0,p.programme160);
   assert.strictEqual(next.detailAt(p,z),detail,'Native collision/render queries share the bounded detail cache');
   assert.deepEqual(detail.context160,plan,'Independent plan/detail caches retain the same geometry after eviction');assert.equal(hash([p,plan]),serialized);
   assert.ok(Object.isFrozen(detail.colliders160.interior)&&Object.isFrozen(detail.colliders160.outdoor));
   const actual=[...detail.interior,...detail.outdoor];added+=actual.length;
   for(const object of actual){assert.equal(object.placementOnly162,undefined,'Placement reservations never become scenery');assert.equal(object.amount,undefined);assert.equal(object.resource,undefined);
    if(!object.solid)continue;solids++;assert.ok(!Geo.rects(plan).some(barrier=>overlap(object,barrier)),object.id+' cannot cover contextual terrain or a service barrier');
   }
   const navPlan={...plan,walls:[...plan.walls,...Geo.rects(plan)]},oldGrid=plan.operations160?.length?Q.accessGrid(before,z,navPlan,old.detailAt(before,z)):null,newGrid=oldGrid?Q.accessGrid(p,z,navPlan,detail):null;
   for(const op of plan.operations160||[]){
    const previousCell=oldGrid?.at(op.anchor.x,op.anchor.y),nextCell=newGrid?.at(op.anchor.x,op.anchor.y);
    if(previousCell>=0&&oldGrid.reachable[previousCell])assert.ok(nextCell>=0&&newGrid.reachable[nextCell],op.kind+' public physical access');
    const anchor=G.global(p,op.anchor.x,op.anchor.y),support=[...plan.objects,...plan.visuals160,...plan.movement160,...plan.gates160].find(item=>item.id===op.supportId);
    assert.equal(next.blocked(anchor.x,anchor.y,.32,z,p.id),old.blocked(anchor.x,anchor.y,.32,z,p.id),op.kind+' working face');
    if(support){const target=G.global(p,support.x+support.w/2,support.y+support.h/2);
     assert.equal(next.line(anchor,target,z,p.id,support.id,.05),old.line(anchor,target,z,p.id,support.id,.05),op.kind+' line of work');}
    services++;
   }
   const object=detail.colliders160.interior.find(item=>{const point=G.global(p,item.x+item.w/2,item.y+item.h/2);return !old.blocked(point.x,point.y,.05,z,p.id);});
   if(object){const point=G.global(p,object.x+object.w/2,object.y+object.h/2);assert.equal(next.blocked(point.x,point.y,.05,z,p.id),true,'New furnishing reaches the actual world collision owner');checkedBodies++;}
  }
 }
 assert.equal(interiors,326);assert.equal(floors,352);assert.ok(added>0&&solids>0&&services>0&&checkedBodies>0);
 console.log('G10_FURNISHING162 '+JSON.stringify({interiors,floors,details:added,solids,services,collisionSites:checkedBodies}));
});

