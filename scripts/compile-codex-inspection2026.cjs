'use strict';
// Ship the existing authoring algorithms, not hundreds of megabytes of repeated plans.
// This compiler removes only the Node I/O boundaries. The full 400 outputs are
// compared against the authoritative generators in codex-inspection2026.test.cjs.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const ROOT = path.resolve(__dirname, '..');
function compile(root = ROOT) {
  const read = name => fs.readFileSync(path.join(root, name), 'utf8');
  const sources = ['scripts/codex-world-foundations2026.cjs', 'scripts/codex-maritime2026.cjs',
    'docs/codex/suivi-monde2026/references-metriques2026.json', 'docs/codex/suivi-monde2026/OBJECTIFS80.json'];
  const texts = sources.map(read);
  const reference = JSON.parse(texts[2]);
  const targets = JSON.parse(texts[3]);
  function body(text, start) {
    const first = text.indexOf(start), last = text.indexOf('\nif(require.main===module)');
    if (first < 0 || last <= first) throw Error('Frontière du générateur auteur introuvable.');
    return text.slice(first, last);
  }
  let foundation = body(texts[0], 'const DATA=');
  const nodeRefs = "function refs(root=path.resolve(__dirname,'..')){return JSON.parse(fs.readFileSync(path.join(root,DATA),'utf8'));}";
  if (foundation.split(nodeRefs).length !== 2) throw Error('Lecture des références ambiguë.');
  foundation = foundation.replace(nodeRefs, 'function refs(){return reference;}');
  const maritime = body(texts[1], 'const RULES=');
  const hash = crypto.createHash('sha256').update(texts.join('\n')).digest('hex');
  const meta = [];
  for (const group of targets.groups) for (const name of group.names) {
    meta.push({id:'EXT-MONDE-T'+String(meta.length+1).padStart(3,'0'), name, domain:group.domain,
      placementRule:group.placementRule, requiredNetworks:group.requiredNetworks, requiredSpaces:group.requiredSpaces});
  }
  const output = `/* Generated by scripts/compile-codex-inspection2026.cjs; edit authoring sources.\n * Source SHA256: ${hash}\n */\n(function(root,factory){'use strict';const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;root.DeadwallCodexLayouts2026=api;})(globalThis,function(){'use strict';
const reference=${JSON.stringify(reference)};
const Foundation=(function(){\n${foundation}\nreturn {TYPES,build,audit,refs,validateReferences};})();
const Maritime=(function(Reference){\n${maritime}\nreturn {PROFILES,build,audit};})(Foundation);
const available=new Set([...Foundation.TYPES,...Object.keys(Maritime.PROFILES)]);
const typologies=${JSON.stringify(meta)}.map(t=>Object.freeze({...t,available:available.has(t.id),variants:50}));
function build(type,number){if(!available.has(type))throw Error('Architecture encore à concevoir.');return Foundation.TYPES.includes(type)?Foundation.build(type,number):Maritime.build(type,number);}
return Object.freeze({version:1,sourceHash:'${hash}',typologies:Object.freeze(typologies),types:Object.freeze([...available]),build,reference:()=>JSON.parse(JSON.stringify(reference)),count:400,scope:'authoring-not-campaign'});
});\n`;
  const destination = path.join(root, 'src/codex-layouts2026.js');
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) fs.writeFileSync(destination, output);
  return {path:destination, bytes:Buffer.byteLength(output), sourceHash:hash, typologies:meta.length, plans:400};
}
if (require.main === module) console.log(JSON.stringify(compile()));
module.exports = {compile};
