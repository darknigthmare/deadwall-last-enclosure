"use strict";
// Ship the authoring algorithms and compare every output with its Node source.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const Registry = require('./codex-generators2026.cjs');
const ROOT = path.resolve(__dirname, '..');
function sourceHash(root = ROOT) {
  return crypto.createHash('sha256').update(Registry.COMPILATION_SOURCES
    .map(name => fs.readFileSync(path.join(root, name), 'utf8')).join('\n')).digest('hex');
}
function compile(root = ROOT) {
  const read = name => fs.readFileSync(path.join(root, name), 'utf8');
  const reference = JSON.parse(read(Registry.REFERENCES));
  const targets = JSON.parse(read(Registry.TARGETS));
  function body(spec) {
    const text = read(spec.path);
    const startMarker = '// BEGIN AUTHOR CORE', endMarker = '// END AUTHOR CORE';
    let first = text.indexOf(startMarker), last = text.indexOf(endMarker);
    if (first >= 0 && last > first) return text.slice(first + startMarker.length, last);
    const start = spec.name === 'Foundation' ? 'const DATA=' : 'const RULES=';
    first = text.indexOf(start); last = text.indexOf('\nif(require.main===module)');
    if (first < 0 || last <= first) throw Error('Frontière du générateur auteur introuvable : ' + spec.path);
    return text.slice(first, last);
  }
  const definitions = Registry.SPECS.map(spec => {
    let core = body(spec);
    if (spec.name === 'Foundation') {
      const nodeRefs = "function refs(root=path.resolve(__dirname,'..')){return JSON.parse(fs.readFileSync(path.join(root,DATA),'utf8'));}";
      if (core.split(nodeRefs).length !== 2) throw Error('Lecture des références ambiguë.');
      core = core.replace(nodeRefs, 'function refs(){return reference;}');
      return `const Foundation=(function(){\n${core}\nreturn {TYPES,build,audit,refs,validateReferences,corridorOverlaps};})();`;
    }
    const exported = spec.name === 'Maritime' ? 'PROFILES,build,audit' : 'TYPES,build,audit';
    return `const ${spec.name}=(function(Reference){\n${core}\nreturn {${exported}};})(Foundation);`;
  });
  const hash = sourceHash(root), meta = [];
  for (const group of targets.groups) for (const name of group.names) {
    meta.push({id:'EXT-MONDE-T'+String(meta.length+1).padStart(3,'0'), name, domain:group.domain,
      placementRule:group.placementRule, requiredNetworks:group.requiredNetworks, requiredSpaces:group.requiredSpaces});
  }
  const generators = Registry.generators();
  const available = generators.flatMap(g => g.types);
  if (available.some(type => !meta.some(t => t.id === type))) throw Error('Typologie produite absente des objectifs.');
  const plans = available.length * Registry.VARIANTS_PER_TYPE;
  const families = Registry.SPECS.map(s => s.name).join(',');
  const output = `/* Generated by scripts/compile-codex-inspection2026.cjs; edit authoring sources.\n * Source SHA256: ${hash}\n */\n(function(root,factory){'use strict';const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;root.DeadwallCodexLayouts2026=api;})(globalThis,function(){'use strict';
const reference=${JSON.stringify(reference)};
${definitions.join('\n')}
const byType=new Map();
for(const generator of [${families}])for(const type of generator.TYPES||Object.keys(generator.PROFILES)){if(byType.has(type))throw Error('Typologie auteur dupliquée.');byType.set(type,generator);}
const typologies=${JSON.stringify(meta)}.map(t=>Object.freeze({...t,available:byType.has(t.id),variants:${Registry.VARIANTS_PER_TYPE}}));
function build(type,number){const generator=byType.get(type);if(!generator)throw Error('Architecture encore à concevoir.');return generator.build(type,number);}
return Object.freeze({version:1,sourceHash:'${hash}',typologies:Object.freeze(typologies),types:Object.freeze([...byType.keys()]),build,reference:()=>JSON.parse(JSON.stringify(reference)),count:byType.size*${Registry.VARIANTS_PER_TYPE},scope:'authoring-not-campaign'});
});\n`;
  const destination = path.join(root, 'src/codex-layouts2026.js');
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) fs.writeFileSync(destination, output);
  return {path:destination, bytes:Buffer.byteLength(output), sourceHash:hash, typologies:meta.length, plans};
}
if (require.main === module) console.log(JSON.stringify(compile()));
module.exports = {compile, sourceHash};
